# Python supports several built-in data types:
#  Integer (int): whole number (e.g., 10, -5).
#  Floats (float): Decimal number (e.g., 3.14, -0.001).
#  string  (str): Text data enclosed in quotes (e.g., "Hello", 'python').
#  Boolean (bool): Represent True or False.
#  List: ordered, mutable collection (e.g., [1, 2, 3]).
#  Tuple: ordered, immutable collection (e.g., (1, 2, 3)).
#  sets: Unordered collection of unique elements (e.g., {1, 2, 3}).
#  Dictionary: key-value pairs (e.g., {"name": "Alice", "age"; 25}).

age = 3
print(age)
print(type(age))

cgpa = 9.6
print(cgpa)
print(type(cgpa))

name = "zaid"
print(name)
print(type(name))

is_completed = True # can also be False
print(is_completed)
print(type(is_completed))









